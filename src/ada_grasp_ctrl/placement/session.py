"""Snapshot-bound candidates, display transforms and orientation-only confirmation."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
import hashlib
import json
from pathlib import Path
from typing import Callable
from uuid import uuid4

import numpy as np


def write_json(path: Path, value: dict) -> None:
    """Atomically replace a finite JSON record in this run's directory."""
    temporary = path.with_name(path.name + "." + uuid4().hex + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def sha256(path: Path) -> str:
    """Identify exact captured or generated bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rotation(value: object) -> np.ndarray:
    """Validate a finite proper rotation without repairing the supplied matrix."""
    matrix = np.asarray(value, dtype=float)
    if (
        matrix.shape != (3, 3)
        or not np.isfinite(matrix).all()
        or not np.allclose(matrix.T @ matrix, np.eye(3), atol=1e-6, rtol=0)
        or not np.isclose(np.linalg.det(matrix), 1, atol=1e-6, rtol=0)
    ):
        raise ValueError("relative_rotation must be a finite SO(3) matrix")
    return matrix


@dataclass(frozen=True)
class PlacementCandidate:
    """Relative active rotation in the captured world frame; no placement translation."""

    candidate_id: str
    source: str
    relative_rotation: list
    object_snapshot_id: str
    frame_id: str = "world"
    support_normal: list | None = None
    plane_parameters: list | None = None
    instance_id: int | None = None
    inlier_count: int | None = None
    inlier_ratio: float | None = None
    metadata: dict = field(default_factory=dict)

    def __post_init__(self) -> None:
        matrix = rotation(self.relative_rotation)
        if self.frame_id != "world" or not self.object_snapshot_id:
            raise ValueError("Candidate requires captured world frame and snapshot ID")
        if self.source not in ("original", "uop_net"):
            raise ValueError("Unknown candidate source")
        if self.source == "original":
            if self.candidate_id != "P00" or not np.array_equal(matrix, np.eye(3)):
                raise ValueError("P00 must retain the original orientation")
        elif (
            self.candidate_id == "P00"
            or self.instance_id is None
            or self.instance_id <= 0
            or self.inlier_count is None
            or self.inlier_count <= 0
            or self.inlier_ratio is None
            or not 0 < self.inlier_ratio <= 1
        ):
            raise ValueError("UOP candidate requires a valid instance and inlier scores")
        for name, size in (("support_normal", 3), ("plane_parameters", 4)):
            value = getattr(self, name)
            if value is not None:
                array = np.asarray(value, dtype=float)
                if array.shape != (size,) or not np.isfinite(array).all():
                    raise ValueError(f"Invalid {name}")
        if self.support_normal is not None and not np.isclose(np.linalg.norm(self.support_normal), 1, atol=1e-6):
            raise ValueError("support_normal must have unit length")


class PlacementSession:
    """Keep all switching independent of inference and the immutable point snapshot."""

    def __init__(self, root: Path, points: np.ndarray, snapshot_id: str, metadata: dict) -> None:
        self.root = root
        self.points = np.array(points, dtype=float, copy=True)
        if self.points.ndim != 2 or self.points.shape[1] != 3 or not len(self.points):
            raise ValueError("Object snapshot must contain Nx3 points")
        if not np.isfinite(self.points).all():
            raise ValueError("Object snapshot must be finite")
        self.points.setflags(write=False)
        self.center = self.points.mean(0)
        self.snapshot_id, self.metadata = snapshot_id, metadata
        self.candidates = [PlacementCandidate("P00", "original", np.eye(3).tolist(), snapshot_id)]
        self.selected_id = "P00"
        self.confirmed_id: str | None = None
        self.inference_status = "not_run"
        self.inference_error: str | None = None

    @property
    def selected(self) -> PlacementCandidate:
        """Return the selected cached candidate."""
        return next(c for c in self.candidates if c.candidate_id == self.selected_id)

    def select(self, candidate_id: str) -> np.ndarray:
        """Switch from the original snapshot, never from the last rendered cloud."""
        if candidate_id not in {c.candidate_id for c in self.candidates}:
            raise ValueError(f"Unknown placement candidate: {candidate_id}")
        self.selected_id = candidate_id
        if candidate_id == "P00":
            return self.points.copy()
        return (self.points - self.center) @ rotation(self.selected.relative_rotation).T + self.center

    def infer_once(self, infer: Callable[[], list[dict]]) -> None:
        """Cache one inference attempt, including failure; P00 is always retained."""
        if self.inference_status != "not_run":
            return
        self.inference_status = "running"
        self.save_candidates()
        try:
            rows = sorted(infer(), key=lambda c: c["instance_id"])
            if len({r["instance_id"] for r in rows}) != len(rows):
                raise ValueError("Duplicate UOP instance IDs")
            candidates = [
                PlacementCandidate(
                    **row, candidate_id=f"P{i:02d}", source="uop_net", object_snapshot_id=self.snapshot_id
                )
                for i, row in enumerate(rows, 1)
            ]
            self.candidates.extend(candidates)
            self.inference_status = "completed" if candidates else "no_plane"
        except Exception as error:
            self.inference_status = "failed"
            self.inference_error = f"{type(error).__name__}: {error}"
        self.save_candidates()

    def save_candidates(self) -> None:
        """Persist the exact same-run plane/rotation pairs for later review."""
        write_json(
            self.root / "candidates.json",
            dict(
                schema_version=1,
                object_snapshot_id=self.snapshot_id,
                metadata=self.metadata,
                inference_status=self.inference_status,
                inference_error=self.inference_error,
                candidates=[asdict(c) for c in self.candidates],
            ),
        )

    def confirm(self) -> Path:
        """Save a reproducible orientation selection; no inference or execution callback."""
        if sha256(self.root / "snapshot.npz") != self.metadata["snapshot_sha256"]:
            raise ValueError("Placement snapshot changed")
        self.save_candidates()
        candidates_hash = sha256(self.root / "candidates.json")
        candidates_file = f"candidates_{candidates_hash}.json"
        immutable = self.root / candidates_file
        if not immutable.exists():
            immutable.write_bytes((self.root / "candidates.json").read_bytes())
        artifact = dict(
            schema_version=1,
            kind="placement_orientation_selection",
            confirmed=True,
            **asdict(self.selected),
            frame_convention=self.metadata,
            preview_pivot_world_m=self.center.tolist(),
            translation_status="undetermined",
            stability_certified=False,
            snapshot_file="snapshot.npz",
            snapshot_sha256=sha256(self.root / "snapshot.npz"),
            candidates_file=candidates_file,
            candidates_sha256=candidates_hash,
        )
        # Keep each explicit confirmation, while selection.json names the latest one.
        artifact["confirmation_id"] = uuid4().hex
        path = self.root / f"selection_{artifact['confirmation_id']}.json"
        write_json(path, artifact)
        write_json(self.root / "selection.json", artifact)
        self.confirmed_id = self.selected_id
        return path

    @classmethod
    def load(cls, root: Path) -> PlacementSession:
        """Reload saved candidates and source cloud without loading a model."""
        record = json.loads((root / "candidates.json").read_text())
        if record.get("schema_version") != 1:
            raise ValueError("Unsupported placement candidate schema")
        metadata = record["metadata"]
        if sha256(root / "snapshot.npz") != metadata["snapshot_sha256"]:
            raise ValueError("Placement snapshot changed")
        with np.load(root / "snapshot.npz", allow_pickle=False) as data:
            session = cls(root, data["object_points_world_m"], record["object_snapshot_id"], metadata)
        candidates = [PlacementCandidate(**row) for row in record["candidates"]]
        if (
            not candidates
            or candidates[0].source != "original"
            or [c.candidate_id for c in candidates] != [f"P{i:02d}" for i in range(len(candidates))]
            or any(c.object_snapshot_id != session.snapshot_id for c in candidates)
            or any(c.source != "uop_net" for c in candidates[1:])
        ):
            raise ValueError("Invalid snapshot-bound candidate list")
        session.candidates = candidates
        session.inference_status = record["inference_status"]
        session.inference_error = record["inference_error"]
        selection = root / "selection.json"
        if selection.exists():
            saved = json.loads(selection.read_text())
            candidate = next(c for c in candidates if c.candidate_id == saved["candidate_id"])
            if (
                saved["object_snapshot_id"] != session.snapshot_id
                or saved["relative_rotation"] != candidate.relative_rotation
            ):
                raise ValueError("Saved placement selection mismatch")
            session.confirmed_id = candidate.candidate_id
        return session
